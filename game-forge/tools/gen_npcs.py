#!/usr/bin/env python3
"""Generate the Game Forge lobby NPCs: one villager on each glowstone block that
offers to take the player to one of the games. Each game is a copy of its studio server's
game living in its own dimension of this world (see tools/port.py and tools/gen_dims.py);
the forge:enter/<game> functions do the move.

Edit the GAMES table, then run from the pack root:  python3 tools/gen_npcs.py
"""
import json
import pathlib

# n, villager name, game shown in the dialog, enter function, glowstone x/z, yaw, profession, blurb.
# enter "workshop" is special: the click opens forge:workshop/open (locked notice, terrain picker, or menu)
# instead of the usual "Take me there!" dialog. FLOOR_Y gives the floor height for NPCs not on the y 63 pads.
GAMES = [
    (1, "Jump Game", "Jump Game", "jump", 23, -7, 0, "farmer",
     "Jump five times to get a big boost!"),
    (2, "One Block", "One Block", "oneblock", 27, -7, 0, "mason",
     "Dig your way to the end of the course with one shovel.\n\n"
     "Once you get to the end, you can make your own obby, or maybe something better!"),
    (3, "PvP Arena", "PvP Arena", "arena", 31, -7, 0, "weaponsmith",
     "Fight your friends in the stadium. Watch out for the magma pads!"),
    (4, "Commands", "Command Forge", "commands", 23, 7, 180, "librarian",
     "Learn Minecraft commands, one quest at a time."),
    (5, "NPCs", "NPC Forge", "npc", 27, 7, 180, "cleric",
     "Make your own characters that talk and run commands."),
    (6, "Command Blocks", "Command Blocks", "command_blocks", 31, 7, 180, "toolsmith",
     "Build machines out of command blocks, one quest at a time."),
    (7, "Workshop", "Personal Workshop", "workshop", 58, 0, 90, "cartographer", ""),
]
FLOOR_Y = {7: 62}  # stands on the sea lantern at the east end of the walkway, facing west

ROOT = pathlib.Path(__file__).resolve().parent.parent
FN = ROOT / "data" / "forge" / "function"


def write(rel, lines):
    p = FN / (rel + ".mcfunction")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines) + "\n")


def snbt_str(s):
    return json.dumps(s)


def heal_lines(n, name, tag, px, py, pz, yaw):
    return [
        f"# {name}",
        f"tp @e[type=villager,tag={tag}] {px} {py} {pz} {yaw} 0",
        "scoreboard players set ok forge_tmp 1",
        f"execute store result score c forge_tmp if entity @e[type=villager,tag={tag}]",
        "execute unless score c forge_tmp matches 1 run scoreboard players set ok forge_tmp 0",
        f"execute store result score c forge_tmp if entity @e[type=interaction,tag={tag}]",
        "execute unless score c forge_tmp matches 1 run scoreboard players set ok forge_tmp 0",
        f"execute if score ok forge_tmp matches 1 run scoreboard players set h{n} forge_tmp 0",
        f"execute if score ok forge_tmp matches 0 positioned {px} {py} {pz} if entity @a[distance=..48] run scoreboard players add h{n} forge_tmp 1",
        f"execute if score h{n} forge_tmp matches 40.. run function forge:internal/spawn{n}",
    ]


clicked = ["# GENERATED by tools/gen_npcs.py. As a click box that was right-clicked: open its game's dialog for the clicker."]
go = ["# GENERATED by tools/gen_npcs.py. As a player who pressed a dialog button: take them to that game."]
heal = ["# GENERATED by tools/gen_npcs.py. Every tick: keep each NPC in place, respawn it if it's gone (killed in creative),",
        "# but only after 40 missing ticks with a player near, because entities load a few ticks after their chunk."]

for n, name, game, enter, x, z, yaw, job, blurb in GAMES:
    px, py, pz = x + 0.5, FLOOR_Y.get(n, 63) + 1, z + 0.5
    tag = f"forge_{n}"

    write(f"internal/spawn{n}", [
        f"# GENERATED by tools/gen_npcs.py. (Re)build the {name} NPC on the block at {x} {py - 1} {z}.",
        f"kill @e[tag={tag}]",
        f"summon villager {px} {py} {pz} {{Tags:[\"forge_npc\",\"{tag}\"],NoAI:1b,Silent:1b,Invulnerable:1b,PersistenceRequired:1b,"
        f"Rotation:[{yaw}f,0f],Offers:{{Recipes:[]}},VillagerData:{{profession:\"minecraft:{job}\",level:5,type:\"minecraft:plains\"}},"
        f"CustomName:{{text:{snbt_str(name)},color:\"gold\",bold:true}},CustomNameVisible:1b}}",
        f"summon interaction {px} {py} {pz} {{Tags:[\"forge_npc\",\"{tag}\"],width:1.0f,height:2.0f,response:1b}}",
        f"scoreboard players set h{n} forge_tmp 0",
    ])

    if enter == "workshop":
        write(f"internal/offer{n}", [
            f"# GENERATED by tools/gen_npcs.py. As the player who clicked the {name} NPC.",
            "function forge:workshop/open",
        ])
        clicked.append(f"execute if entity @s[tag={tag}] on target run function forge:internal/offer{n}")
        heal += heal_lines(n, name, tag, px, py, pz, yaw)
        continue

    body = f"{blurb}\n\nWant to play {game}? I can take you there."
    dialog = (
        "{type:\"minecraft:confirmation\","
        f"title:{{text:{snbt_str(name)},color:\"gold\",bold:true}},external_title:{snbt_str(name)},pause:false,"
        f"body:[{{type:\"minecraft:plain_message\",width:300,contents:{snbt_str(body)}}}],"
        f"yes:{{label:{{text:\"Take me there!\",color:\"green\"}},action:{{type:\"minecraft:run_command\",command:\"trigger forge_go set {n}\"}}}},"
        "no:{label:\"Not now\"}}"
    )
    write(f"internal/offer{n}", [
        f"# GENERATED by tools/gen_npcs.py. As the player who clicked the {name} NPC.",
        "scoreboard players enable @s forge_go",
        f"dialog show @s {dialog}",
    ])

    clicked.append(f"execute if entity @s[tag={tag}] on target run function forge:internal/offer{n}")
    go.append(f"execute if score @s forge_go matches {n} run function forge:enter/{enter}")

    heal += heal_lines(n, name, tag, px, py, pz, yaw)

clicked.append("data remove entity @s interaction")

go.append("scoreboard players reset @s forge_go")

write("internal/clicked", clicked)
write("internal/go", go)
write("internal/heal", heal)
print("wrote", len(GAMES), "NPCs")
