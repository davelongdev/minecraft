#!/usr/bin/env python3
"""Generate the PvP Arena stadium build functions.

Run from the pack root:  python3 tools/gen_stadium.py

Writes data/arena/function/internal/:
  clear.mcfunction       air over the whole stadium box, so a rebuild removes anything added or broken
  build.mcfunction       pass 1: every solid column, tops as plain stone, barrier ring, light towers
  build2.mcfunction      pass 2 (a second later): the real top blocks (floor, seats, aisles, caps, rim band).
                         Void chunks keep stale skylight, so a block placed once can stay black;
                         changing the top block again relights it.
  pads_build.mcfunction  the eight 3x3 magma piston pads (sticky piston at y 63, magma at y 64)
  pads_up_a / pads_down_a / pads_up_b / pads_down_b   redstone block under a group = push up
  pads_warn_a / pads_warn_b                           flame particles over a group before it fires
  stands_tp.mcfunction   send @s to the stands spawn (top of the south aisle)

Layout (centre block 0,0; r = distance of the block from the centre block):
  r <= 20.5   arena floor, top y 64 (base y 61..63)
  r <= 21.5   arena wall up to y 68, barrier ring y 69..95 keeps fighters in and the stands out
  r <= 34.5   13 tiers of seats, tier k top at y 68+k; aisles where |x|<=1 or |z|<=1
  r <= 36.5   outer rim up to y 84 (red concrete band on the west half, blue on the east)
  four light towers on the diagonals, froglight heads at y 95..96
"""
import math
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "arena", "function", "internal")

FLOOR_R = 20.5
WALL_R = 21.5
STANDS_R = 34.5
RIM_R = 36.5
BASE_Y = 61
FLOOR_Y = 64
WALL_TOP = 68
RIM_TOP = 84
BARRIER_TOP = 95
SPAWN = (0, 80, 33)          # stand position (block) at the top of the south aisle
PAD_R = 11
TOWERS = [(26, 26), (-27, 26), (-27, -27), (26, -27)]


def tier(r):
    return math.ceil(r - WALL_R) - 1


def outward(x, z):
    """Cardinal direction pointing away from the centre (stair backs face outward)."""
    if abs(z) >= abs(x):
        return "south" if z > 0 else "north"
    return "east" if x > 0 else "west"


def columns():
    """(x, z) -> (kind, solid_top_y, top_block) for every column of the stadium."""
    cols = {}
    n = int(RIM_R) + 1
    for x in range(-n, n + 1):
        for z in range(-n, n + 1):
            r = math.hypot(x, z)
            if r <= FLOOR_R:
                if r <= 2.5:
                    top = "chiseled_red_sandstone"
                elif r > FLOOR_R - 1:
                    top = "cut_red_sandstone"
                else:
                    top = "smooth_sandstone"
                cols[(x, z)] = ("stone", FLOOR_Y - 1, FLOOR_Y, top)
            elif r <= WALL_R:
                cols[(x, z)] = ("polished_blackstone_bricks", WALL_TOP - 1, WALL_TOP, "chiseled_polished_blackstone")
            elif r <= STANDS_R:
                k = tier(r)
                y = WALL_TOP + k
                face = outward(x, z)
                if abs(x) <= 1 or abs(z) <= 1:
                    top = f"polished_andesite_stairs[facing={face}]"
                elif x < 0:
                    top = f"red_nether_brick_stairs[facing={face}]"
                else:
                    top = f"dark_prismarine_stairs[facing={face}]"
                cols[(x, z)] = ("stone_bricks", y - 1, y, top)
            elif r <= RIM_R:
                cols[(x, z)] = ("stone_bricks", RIM_TOP - 1, RIM_TOP, "polished_andesite")
    return cols


def runs(cells):
    """cells: dict (x, y0, y1, z) -> block. Merge runs along x into fill commands."""
    out = []
    keys = sorted(cells, key=lambda k: (k[3], k[1], k[2], cells[k], k[0]))
    i = 0
    while i < len(keys):
        x, y0, y1, z = keys[i]
        block = cells[keys[i]]
        j = i
        while (j + 1 < len(keys)
               and keys[j + 1][1:] == (y0, y1, z)
               and keys[j + 1][0] == keys[j][0] + 1
               and cells[keys[j + 1]] == block):
            j += 1
        x1 = keys[j][0]
        if x1 == x and y0 == y1:
            out.append(f"setblock {x} {y0} {z} {block}")
        else:
            out.append(f"fill {x} {y0} {z} {x1} {y1} {z} {block}")
        i = j + 1
    return out


def write(name, lines, header):
    path = os.path.join(OUT, name + ".mcfunction")
    with open(path, "w") as f:
        f.write("# Generated by tools/gen_stadium.py - edit the Python, not this file.\n")
        for h in header:
            f.write(f"# {h}\n")
        f.write("\n".join(lines) + "\n")


def pads():
    pts = []
    for i in range(8):
        a = math.radians(45 * i)
        pts.append((round(PAD_R * math.cos(a)), round(PAD_R * math.sin(a))))
    return pts


def main():
    os.makedirs(OUT, exist_ok=True)
    cols = columns()

    # clear: air over the whole stadium box (towers included), in slabs under the 32768-block fill limit
    n = int(RIM_R) + 1
    top_y = BARRIER_TOP + 1
    span = 2 * n + 1
    step = 32768 // (span * span)
    clear = []
    for y in range(BASE_Y, top_y + 1, step):
        clear.append(f"fill {-n} {y} {-n} {n} {min(y + step - 1, top_y)} {n} air")
    write("clear", clear, ["Empties the stadium box before a rebuild (run by build_start)."])

    # pass 1: solid columns with a plain stone top, then barrier ring and towers
    solid, tops = {}, {}
    for (x, z), (mat, y_solid, y_top, _) in cols.items():
        solid[(x, BASE_Y, y_solid, z)] = mat
        tops[(x, y_top, y_top, z)] = "stone"
    p1 = runs(solid) + runs(tops)
    barrier = {}
    for (x, z), (mat, *_ ) in cols.items():
        if mat == "polished_blackstone_bricks":
            barrier[(x, WALL_TOP + 1, BARRIER_TOP, z)] = "barrier"
    p1 += runs(barrier)
    for tx, tz in TOWERS:
        p1.append(f"fill {tx} {BASE_Y} {tz} {tx + 1} {BARRIER_TOP - 1} {tz + 1} polished_blackstone")
        p1.append(f"fill {tx - 1} {BARRIER_TOP} {tz - 1} {tx + 2} {BARRIER_TOP + 1} {tz + 2} pearlescent_froglight")
    p1.append("function arena:internal/pads_build")
    write("build", p1, ["Pass 1 of the stadium; build2 runs about a second later (internal/tick)."])

    # pass 2: real tops + the rim's coloured band
    tops2, band = {}, {}
    for (x, z), (mat, _, y_top, top) in cols.items():
        tops2[(x, y_top, y_top, z)] = top
        if top == "polished_andesite":
            band[(x, RIM_TOP - 2, RIM_TOP - 1, z)] = "red_concrete" if x < 0 else "blue_concrete"
    write("build2", runs(tops2) + runs(band) + ["function arena:internal/pads_build"],
          ["Pass 2: top blocks (relights them) and the rim band."])

    # piston pads
    pts = pads()
    build = []
    for x, z in pts:
        build += [
            f"fill {x - 1} 62 {z - 1} {x + 1} 62 {z + 1} stone",
            f"fill {x - 1} 63 {z - 1} {x + 1} 63 {z + 1} sticky_piston[facing=up]",
            f"fill {x - 1} 64 {z - 1} {x + 1} 64 {z + 1} magma_block",
            f"fill {x - 1} 65 {z - 1} {x + 1} 65 {z + 1} air",
        ]
    write("pads_build", build, ["Eight 3x3 pads: stone y 62 (redstone block slot), sticky pistons y 63, magma y 64."])
    groups = {"a": pts[0::2], "b": pts[1::2]}
    for g, gp in groups.items():
        write(f"pads_up_{g}", [f"fill {x - 1} 62 {z - 1} {x + 1} 62 {z + 1} redstone_block" for x, z in gp],
              [f"Group {g.upper()} up: a redstone block under each piston."])
        write(f"pads_down_{g}", [f"fill {x - 1} 62 {z - 1} {x + 1} 62 {z + 1} stone" for x, z in gp],
              [f"Group {g.upper()} down: the sticky pistons pull the magma back."])
        write(f"pads_warn_{g}", [f"particle flame {x + 0.5} 65.1 {z + 0.5} 1 0 1 0.01 3" for x, z in gp],
              [f"Flames over group {g.upper()} before it pushes up."])

    sx, sy, sz = SPAWN
    write("stands_tp", [
        f"tp @s {sx + 0.5} {sy} {sz + 0.5} facing 0.5 66 0.5",
        f"spawnpoint @s {sx} {sy} {sz}",
    ], ["Top of the south aisle, facing the arena."])
    print(f"pass 1: {len(p1)} commands, pass 2: {len(tops2)} cells, pads: {pts}")


if __name__ == "__main__":
    main()
