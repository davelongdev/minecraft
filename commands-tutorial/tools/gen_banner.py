#!/usr/bin/env python3
"""Generate data/tut/function/internal/banner_rel.mcfunction: block letters spelling
COMMAND / FORGE floating in the void east of each island, facing the player.

Run from commands-tutorial/:  python3 tools/gen_banner.py

Coordinates are relative to the island origin (the function runs positioned there).
The player spawns on the west edge facing east, so columns advance in +z (their right).
"""
from pathlib import Path

# 5-row pixel glyphs; '#' = block. Widths vary (M is 5, N is 4, the rest 3).
GLYPHS = {
    "C": ["###", "#..", "#..", "#..", "###"],
    "O": ["###", "#.#", "#.#", "#.#", "###"],
    "M": ["#...#", "##.##", "#.#.#", "#...#", "#...#"],
    "A": ["###", "#.#", "###", "#.#", "#.#"],
    "N": ["#..#", "##.#", "#.##", "#..#", "#..#"],
    "D": ["##.", "#.#", "#.#", "#.#", "##."],
    "F": ["###", "#..", "##.", "#..", "#.."],
    "R": ["##.", "#.#", "##.", "#.#", "#.#"],
    "G": ["###", "#..", "#.#", "#.#", "###"],
    "E": ["###", "#..", "##.", "#..", "###"],
}
GAP = 1            # columns between letters
X = 20             # blocks east of the island origin (island is x 0..11)
CENTER_Z = 5.5     # island centre line (island is z 0..11)
LINES = [          # (text, bottom row y offset, block)
    ("COMMAND", 10, "magma_block"),
    ("FORGE", 3, "magma_block"),
]
MARKER_LINE = 1    # index into LINES whose bottom-left block ensure_plot checks


def rows_for(text):
    """Return list of 5 strings, the text rendered left→right with gaps."""
    rows = [""] * 5
    for i, ch in enumerate(text):
        g = GLYPHS[ch]
        for r in range(5):
            rows[r] += ("." * GAP if i else "") + g[r]
    return rows


def main():
    out = [
        "# GENERATED by tools/gen_banner.py — edit the Python, not this file.",
        "# Block letters east of the island, facing the player. Positioned at the island origin.",
        "# Cleared and rebuilt with the island (build_plot_rel) and by ensure_plot if the chunk wasn't loaded.",
    ]
    bounds = []
    for text, y0, block in LINES:
        rows = rows_for(text)
        width = len(rows[0])
        z0 = round(CENTER_Z - width / 2)
        bounds.append((z0, z0 + width - 1, y0, y0 + 4))
    zmin = min(b[0] for b in bounds) - 1
    zmax = max(b[1] for b in bounds) + 1
    ymin = min(b[2] for b in bounds) - 1
    ymax = max(b[3] for b in bounds) + 1
    out.append(f"fill ~{X} ~{ymin} ~{zmin} ~{X} ~{ymax} ~{zmax} air")
    marker = None
    for (text, y0, block), (z0, _, _, _) in zip(LINES, bounds):
        rows = rows_for(text)
        out.append(f"# {text}")
        for r, row in enumerate(rows):
            y = y0 + (4 - r)          # row 0 is the top
            c = 0
            while c < len(row):
                if row[c] == "#":
                    start = c
                    while c < len(row) and row[c] == "#":
                        c += 1
                    out.append(f"fill ~{X} ~{y} ~{z0 + start} ~{X} ~{y} ~{z0 + c - 1} {block}")
                else:
                    c += 1
        if LINES.index((text, y0, block)) == MARKER_LINE:
            marker = (X, y0, z0, block)   # bottom-left pixel; every glyph's left column is solid
    Path("data/tut/function/internal/banner_rel.mcfunction").write_text("\n".join(out) + "\n")
    x, y, z, block = marker
    print(f"wrote banner_rel.mcfunction ({len(out)} lines); marker block: ~{x} ~{y} ~{z} {block}")


if __name__ == "__main__":
    main()
